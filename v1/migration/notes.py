"""
migration.notes
---------------
Note (comment) migration.

Each note is posted by its own author's PAT with the original `created_at`, so
the destination thread reads exactly like the source. Notes are serial within
one issue — their order is what makes the `skip_existing` resume offset
meaningful — and concurrent across issues.
"""

import aiohttp

from .logging_setup import log


class NotesMixin:
    """
    Note migration for GitLabMigration.

    Expects the host object to provide `cfg`, both URLs, both tokens, and both
    project IDs.
    """

    # ---------------------------------------------------------------- #
    # [4] Note Migration — Author PAT + Original Timestamp
    # ---------------------------------------------------------------- #

    async def _dest_note_count(
        self,
        session: aiohttp.ClientSession,
        dest_iid
    ) -> int:
        """
        Count user-authored notes already present on a destination issue.

        System notes (state changes, label updates) are excluded because they
        are generated by the destination instance, not migrated.

        Args:
            session:  Active aiohttp session.
            dest_iid: Destination issue IID.

        Returns:
            Number of non-system notes.
        """
        try:
            notes = await self._get_all_pages(
                session,
                f"{self.dest_url}/api/v4/projects/{self.dest_project}"
                f"/issues/{dest_iid}/notes",
                self.dest_token
            )
        except Exception as exc:
            log.warning(
                f"    Could not count existing notes on #{dest_iid}: {exc}"
            )
            return 0

        return sum(1 for note in notes if not note.get("system", False))

    async def migrate_notes(
        self,
        session: aiohttp.ClientSession,
        source_iid: int,
        dest_iid: int,
        skip_existing: int = 0
    ) -> int:
        """
        Migrate all notes/comments from a source issue to a destination issue.

        Each note is posted by its own author's PAT with the original
        `created_at`, so the destination thread reads exactly like the source.
        A note whose author has no usable PAT is posted by DEST_TOKEN with a
        markdown attribution header recording the original author, timestamp,
        and source issue URL.

        Notes are requested with `sort=asc` so the API returns them oldest
        first, rather than relying on reversing a newest-first page set — which
        only works while every note fits in a single page.

        System-generated notes (state changes, label updates, and similar) are
        skipped: the destination generates its own.

        Notes must be created serially within an issue so their order — and
        therefore any `skip_existing` resume offset — stays meaningful.

        Args:
            session:       Active aiohttp session.
            source_iid:    Source issue IID.
            dest_iid:      Destination issue IID.
            skip_existing: Number of leading notes already on the destination,
                           used when adopting a partially migrated issue.

        Returns:
            Number of notes successfully migrated by this call.
        """
        notes_url = (
            f"{self.source_url}/api/v4/projects/"
            f"{self.source_project}/issues/{source_iid}/notes"
            f"?sort=asc&order_by=created_at"
        )

        try:
            notes = await self._get_all_pages(
                session, notes_url, self.source_token
            )
        except Exception as exc:
            log.warning(
                f"Could not fetch notes for source issue #{source_iid}: {exc}"
            )
            return 0

        dest_notes_url = (
            f"{self.dest_url}/api/v4/projects/"
            f"{self.dest_project}/issues/{dest_iid}/notes"
        )

        user_notes = [n for n in notes if not n.get("system", False)]

        if skip_existing:
            if skip_existing >= len(user_notes):
                log.debug(
                    f"    All {len(user_notes)} note(s) on #{source_iid} are "
                    f"already present."
                )
                return 0
            log.debug(
                f"    Resuming notes on #{source_iid} at {skip_existing + 1} "
                f"of {len(user_notes)}."
            )
            user_notes = user_notes[skip_existing:]

        migrated = 0

        for note in user_notes:
            author     = note.get("author", {}).get("username", "unknown")
            created_at = note.get("created_at", "")
            token, fidelity = self.token_for_author(author)

            body = await self.rewrite_uploads(
                session, note.get("body", "").strip(), source_iid
            )
            if fidelity == "admin_attributed":
                body = self.attribution_header(
                    author, created_at or "unknown", source_iid, "note"
                ) + body

            if self.cfg["DRY_RUN"]:
                log.debug(
                    f"    [DRY RUN] Would migrate note by {author} "
                    f"on issue #{source_iid} ({fidelity})"
                )
                migrated += 1
                continue

            payload = {"body": body}
            if created_at:
                payload["created_at"] = created_at

            try:
                await self._post(session, dest_notes_url, token, payload)
                migrated += 1
            except Exception as exc:
                log.warning(
                    f"    Failed to migrate note by {author} on issue "
                    f"#{source_iid}: {exc}"
                )

        return migrated
